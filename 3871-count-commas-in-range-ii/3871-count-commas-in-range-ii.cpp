class Solution {
public:
    long long countCommas(long long n) {
         long long count = 1;
         if(n<1000 )
         {
            return 0; 
         }
         if(n>999 && n<=999999){
            count = n - 999;
         }
         if(n>999999&&n<=999999999)
         {
            count = 2*(n-999999)+999000;
         }
         if(n>999999999&&n<=999999999999)
         {
            count = 3*(n-999999999) +2*(999000000)+999000;
         }
         if(n>999999999999&&n<=999999999999999)
         {
            count = 4*(n-999999999999)+ 3*(999000000000) +2*(999000000)+999000;
         }
         if(n>999999999999999&&n<=999999999999999999)
         {
            count =  5*(n-999999999999999) +4*(999000000000000)+ 3*(999000000000) +2*(999000000)+999000;
         }
         
        return count;
        
    }
};